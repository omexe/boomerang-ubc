// Copies the compiled ABIs of Boomerang and PledgeRouter into src/abi.ts as `as const`
// arrays, so the kit ships the exact ABI the contracts compiled to. Run it after
// `hardhat build` regenerates the artifacts. It never edits the artifacts.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifacts = resolve(here, "../../../contracts/artifacts/contracts");

// Each entry: the exported name in abi.ts and the artifact that holds its ABI.
const sources = [
  { name: "boomerangAbi", path: resolve(artifacts, "Boomerang.sol/Boomerang.json") },
  { name: "routerAbi", path: resolve(artifacts, "PledgeRouter.sol/PledgeRouter.json") },
];

function readAbi(file) {
  let raw;
  try {
    raw = readFileSync(file, "utf8");
  } catch {
    console.error(`sync-abi: artifact not found: ${file}\nRun \`hardhat build\` in contracts/ first.`);
    process.exit(1);
  }
  const artifact = JSON.parse(raw);
  if (!Array.isArray(artifact.abi)) {
    console.error(`sync-abi: artifact has no abi array: ${file}`);
    process.exit(1);
  }
  return artifact.abi;
}

const parts = sources.map(({ name, path }) => {
  const abi = readAbi(path);
  return `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;`;
});

const header = "// Generated by scripts/sync-abi.mjs from the compiled contracts. Do not edit.\n";
const out = resolve(here, "../src/abi.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, header + "\n" + parts.join("\n\n") + "\n");
console.log(`sync-abi: wrote ${out} (${sources.map((s) => s.name).join(", ")})`);
